"""Train the final spell network on every recording and export it.  python3 train.py data.json [eval.json]

Writes:
  firmware/LarpCharm/spells_model.h   weights (batch norm folded in), class prototypes, 5 DTW recordings per
                                      spell and the decision thresholds, for the charm
  spells-model.js                     the same, for the website (window.SPELL_MODEL, float32 in base64)
  model/spells_cnn.pt                 the PyTorch weights
  model/model.json                    what it was trained on, and the cross-validated metrics (from evaluate.py)
  model/testvec.h, model/testvec.json takes with the fingerprints PyTorch gives them, to check the C and JS ports
"""
import base64, json, os, sys, datetime
import numpy as np, torch
from spells_data import load
from spells_model import BASE, T, segment, to_input, Net, train, embed, prototypes, ACT_DPS, PAD, LEAD
from dtw import dist, dtw_feat

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
HERE = os.path.dirname(os.path.abspath(__file__))
BASE_THR, TEACH_SPREAD, TEACH_MIN_SIM, TPL_PER_SPELL, TPL_SCALE = 0.85, 2.0, 0.3, 5, 2048.0

takes = load(sys.argv[1])
base = [t for t in takes if t['label'] in BASE]
S = [segment(t['x']) for t in base]; Y = np.array([BASE.index(t['label']) for t in base])
loss = []
net = train(S, Y, epochs=160, seed=0, log=loss)
E = embed(net, S); P = prototypes(E, Y, len(BASE))
acc = np.mean((E @ P.T).argmax(1) == Y)
print(f'trained on {len(base)} takes, final loss {loss[-1]:.3f}, training accuracy {acc * 100:.1f}%')

# fold batch norm into the convolutions
layers = []
for blk in net.f:
    conv, bn = blk[0], blk[1]
    s = (bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach()
    w = (conv.weight.detach() * s[:, None, None]).numpy().astype(np.float32)
    b = ((conv.bias.detach() - bn.running_mean) * s + bn.bias.detach()).numpy().astype(np.float32)
    layers.append(dict(w=w, b=b, k=conv.kernel_size[0], s=conv.stride[0], p=conv.padding[0], i=conv.in_channels, o=conv.out_channels))
lw = net.e.weight.detach().numpy().astype(np.float32); lb = net.e.bias.detach().numpy().astype(np.float32)

# a numpy forward pass with the folded weights: must match PyTorch (it is what C and JS do)
def np_embed(x):
    h = x
    for L in layers:
        n_out = (h.shape[1] + 2 * L['p'] - L['k']) // L['s'] + 1
        hp = np.pad(h, ((0, 0), (L['p'], L['p'])))
        out = np.zeros((L['o'], n_out), np.float32)
        for k in range(L['k']): out += np.einsum('oi,it->ot', L['w'][:, :, k], hp[:, k:k + L['s'] * (n_out - 1) + 1:L['s']])
        h = np.maximum(out + L['b'][:, None], 0)
    e = lw @ h.mean(1) + lb
    return e / np.linalg.norm(e)
chk = max(np.abs(np_embed(to_input(S[i])) - E[i]).max() for i in range(0, len(S), 9))
print(f'folded weights vs pytorch: max difference {chk:.2e}')
assert chk < 1e-4

# 5 stored recordings per spell for DTW (the medoids: closest on average to the rest of their class)
tpl = []
for c, name in enumerate(BASE[:-1]):
    idx = np.where(Y == c)[0]; F = [dtw_feat(S[i]) for i in idx]
    tot = [sum(dist(F[a], F[b]) for b in range(len(F)) if b != a) for a in range(len(F))]
    for a in np.argsort(tot)[:TPL_PER_SPELL]: tpl.append((c, F[a]))
n_params = sum(p.numel() for p in Net().parameters())

# the constellation: a 2D map of the fingerprint space (PCA of the training fingerprints), with stars for some takes
map_mean = E.mean(0).astype(np.float32); _, _, Vt = np.linalg.svd(E - map_mean, full_matrices=False); map_v = Vt[:2].astype(np.float32)
Z = (E - map_mean) @ map_v.T
map_pts = []
for c in range(len(BASE)):
    idx = np.where(Y == c)[0]
    for i in idx[np.linspace(0, len(idx) - 1, min(10, len(idx))).astype(int)]: map_pts.append((Z[i, 0], Z[i, 1], c))
map_lo, map_hi = Z.min(0) - 0.08, Z.max(0) + 0.08

# ── C header ──
def cfloat(v):
    t = f'{float(v):.8g}'
    return (t if ('.' in t or 'e' in t or 'n' in t) else t + '.0') + 'f'
def carr(name, a, ctype='float', fmt=None):
    flat = np.asarray(a).ravel(); vals = [cfloat(v) for v in flat] if fmt is None else [fmt.format(v) for v in flat]
    lines = [', '.join(vals[i:i + 10]) for i in range(0, len(vals), 10)]
    return f'static const {ctype} {name}[{len(flat)}] = {{\n  ' + ',\n  '.join(lines) + '\n};\n'
stamp = datetime.date.today().isoformat()
h = [f'// Generated by firmware/tools/spells/train.py on {stamp}: the spell network, {n_params:,} parameters,',
     f'// trained on {len(base)} recorded takes. Batch norm is folded into the convolutions. Do not edit by hand.',
     '#pragma once', '#include <stdint.h>', '',
     f'#define SPL_T {T}', f'#define SPL_IN 7', f'#define SPL_EMB {lw.shape[0]}', f'#define SPL_CLASSES {len(BASE)}', f'#define SPL_NONE {BASE.index("none")}',
     f'#define SPL_ACT_DPS {ACT_DPS:.1f}f', f'#define SPL_PAD {PAD}', f'#define SPL_LEAD {LEAD}',
     f'#define SPL_BASE_THR {BASE_THR}f', f'#define SPL_TEACH_SPREAD {TEACH_SPREAD}f', f'#define SPL_TEACH_MIN_SIM {TEACH_MIN_SIM}f',
     f'#define SPL_TPL_N {len(tpl)}', f'#define SPL_TPL_SCALE {TPL_SCALE:.1f}f', '',
     'static const char *const SPL_NAMES[SPL_CLASSES] = {' + ', '.join(f'"{b}"' for b in BASE) + '};',
     'struct SplLayer { const float *w, *b; int in, out, k, stride, pad; };', '']
for i, L in enumerate(layers):
    h.append(carr(f'SPL_C{i}_W', L['w'])); h.append(carr(f'SPL_C{i}_B', L['b']))
h.append(f'static const SplLayer SPL_LAYERS[{len(layers)}] = {{' + ', '.join(f"{{SPL_C{i}_W, SPL_C{i}_B, {L['i']}, {L['o']}, {L['k']}, {L['s']}, {L['p']}}}" for i, L in enumerate(layers)) + '};')
h.append(f'#define SPL_LAYERS_N {len(layers)}')
h.append(carr('SPL_LIN_W', lw)); h.append(carr('SPL_LIN_B', lb)); h.append(carr('SPL_PROTO', P))
off, data = [], []
for c, f in tpl: off.append((c, len(data) // 6, len(f))); data += list(np.clip(np.round(f.ravel() * TPL_SCALE), -32767, 32767).astype(int))
h.append(carr('SPL_TPL_DATA', data, 'int16_t', '{:d}'))
h.append('// the constellation: fingerprint -> 2D (PCA), the box it fits in, and stars (x, y, class) for some training takes')
h.append(carr('SPL_MAP_MEAN', map_mean)); h.append(carr('SPL_MAP_V', map_v))
h.append(f'static const float SPL_MAP_BOX[4] = {{{map_lo[0]:.6f}f, {map_lo[1]:.6f}f, {map_hi[0]:.6f}f, {map_hi[1]:.6f}f}};')
h.append(carr('SPL_MAP_PTS', [v for pt in map_pts for v in pt])); h.append(f'#define SPL_MAP_N {len(map_pts)}')
h.append('// recording: class, first row, rows (6 channels per row, at 50 Hz)')
h.append(carr('SPL_TPL_INFO', [v for o in off for v in o], 'uint16_t', '{:d}'))
open(os.path.join(ROOT, 'firmware', 'LarpCharm', 'spells_model.h'), 'w').write('\n'.join(h))

# ── website ──
b64 = lambda a: base64.b64encode(np.ascontiguousarray(a, np.float32).tobytes()).decode()
js = {'version': stamp, 'params': n_params, 'classes': BASE, 'T': T, 'actDps': ACT_DPS, 'pad': PAD, 'lead': LEAD,
      'baseThr': BASE_THR, 'teachSpread': TEACH_SPREAD, 'teachMinSim': TEACH_MIN_SIM,
      'layers': [dict(w=b64(L['w']), b=b64(L['b']), i=L['i'], o=L['o'], k=L['k'], s=L['s'], p=L['p']) for L in layers],
      'linW': b64(lw), 'linB': b64(lb), 'emb': int(lw.shape[0]), 'proto': b64(P),
      'tpl': [dict(c=int(c), d=b64(f)) for c, f in tpl],
      'map': {'mean': b64(map_mean), 'v': b64(map_v), 'box': [float(map_lo[0]), float(map_lo[1]), float(map_hi[0]), float(map_hi[1])],
              'pts': [[round(float(x), 4), round(float(y), 4), int(c)] for x, y, c in map_pts]}}
if len(sys.argv) > 2:
    ev = json.load(open(sys.argv[2])); sw = next(x for x in ev['base']['sweep'] if abs(x['threshold'] - BASE_THR) < 1e-6)
    js['metrics'] = {'takes': ev['takes'], 'spells_right': sw['spells_right'], 'spells_wrong': sw['spells_wrong'], 'none_rejected': sw['none_rejected'],
                     'teach': ev['teach']['average']['hybrid'], 'teach_cnn': ev['teach']['average']['cnn'], 'teach_dtw': ev['teach']['average']['dtw']}
open(os.path.join(ROOT, 'spells-model.js'), 'w').write(f'// Generated by firmware/tools/spells/train.py on {stamp}: the spell network for the website ({n_params:,} parameters).\n'
    f'// The same weights as firmware/LarpCharm/spells_model.h; spells-net.js runs it. Do not edit by hand.\nwindow.SPELL_MODEL = {json.dumps(js)};\n')

# ── PyTorch weights, metrics, test vectors ──
torch.save(net.state_dict(), os.path.join(HERE, 'model', 'spells_cnn.pt'))
meta = {'trained': stamp, 'parameters': n_params, 'takes': len(base), 'per_class': {b: int((Y == i).sum()) for i, b in enumerate(BASE)},
        'epochs': 160, 'final_loss': loss[-1], 'thresholds': {'base': BASE_THR, 'teach_spread': TEACH_SPREAD, 'teach_min_sim': TEACH_MIN_SIM},
        'sessions': sorted({t['session'] for t in base})}
if len(sys.argv) > 2: meta['evaluation'] = json.load(open(sys.argv[2]))
json.dump(meta, open(os.path.join(HERE, 'model', 'model.json'), 'w'), indent=1)
pick = [int(np.where(Y == c)[0][0]) for c in range(len(BASE))] + [int(np.where(Y == 2)[0][3])]
tv = [{'label': base[i]['label'], 'raw': np.round(np.concatenate([base[i]['x'][:, :3] * 4096, base[i]['x'][:, 3:] * 16], 1)).astype(int).ravel().tolist(),
       'n': len(base[i]['x']), 'emb': E[i].tolist()} for i in pick]
json.dump(tv, open(os.path.join(HERE, 'model', 'testvec.json'), 'w'))
with open(os.path.join(HERE, 'model', 'testvec.h'), 'w') as f:
    f.write('// Generated by train.py: takes and their PyTorch fingerprints, for test_engine.c\n')
    for k, t in enumerate(tv):
        f.write(f"static const int16_t TV{k}[] = {{{', '.join(map(str, t['raw']))}}};\nstatic const float TV{k}_E[] = {{{', '.join(f'{v:.7g}f' for v in t['emb'])}}};\n")
    f.write(f'static const struct {{ const char *label; const int16_t *raw; int n; const float *emb; }} TV[] = {{' +
            ', '.join(f'{{"{t["label"]}", TV{k}, {t["n"]}, TV{k}_E}}' for k, t in enumerate(tv)) + f'}};\n#define TV_N {len(tv)}\n')
print('wrote spells_model.h, spells-model.js, model/spells_cnn.pt, model/model.json, model/testvec.*')
