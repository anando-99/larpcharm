#!/usr/bin/env python3
"""Turn the weather-pup sprite sheet into firmware + web data.

  python3 firmware/tools/mksprite.py firmware/tools/pup_sheet.png

Finds the 8 sprites on the sheet (transparent background, 4x2 grid), scales
them to a common height, builds one shared palette (index 0 = transparent)
and writes:
  firmware/LarpCharm/pup_sprite.h   RGB565 palette + 8-bit pixels (PROGMEM)
  pup.js                            the same data for the web preview
Outfit order: hot, warm, mild, cool, freezing, rain, snow, night.
Needs Pillow + numpy.
"""
import base64, os, sys
from collections import deque
import numpy as np
from PIL import Image

TARGET_H = int(os.environ.get('PUP_H', 70))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES = ['hot', 'warm', 'mild', 'cool', 'freezing', 'rain', 'snow', 'night']


def blobs(alpha):
    H, W = alpha.shape
    lab = np.zeros((H, W), np.int32)
    out, n = [], 0
    for y in range(H):
        for x in range(W):
            if alpha[y, x] and not lab[y, x]:
                n += 1
                q = deque([(y, x)]); lab[y, x] = n
                x0 = x1 = x; y0 = y1 = y; c = 0
                while q:
                    cy, cx = q.popleft(); c += 1
                    x0, x1, y0, y1 = min(x0, cx), max(x1, cx), min(y0, cy), max(y1, cy)
                    for dy in (-1, 0, 1):
                        for dx in (-1, 0, 1):
                            ny, nx = cy + dy, cx + dx
                            if 0 <= ny < H and 0 <= nx < W and alpha[ny, nx] and not lab[ny, nx]:
                                lab[ny, nx] = n; q.append((ny, nx))
                out.append((c, x0, y0, x1, y1))
    return out


def main(src):
    im = Image.open(src).convert('RGBA')
    a = np.array(im)
    boxes = [b for b in blobs(a[:, :, 3] > 100) if b[0] > 200]
    rowh = im.height // 2
    boxes.sort(key=lambda b: (b[2] // rowh, b[1]))
    if len(boxes) != 8:
        sys.exit('expected 8 sprites, found %d' % len(boxes))
    # common scale so the tallest sprite is TARGET_H; sprites sit on a shared baseline
    tall = max(b[4] - b[2] + 1 for b in boxes)
    k = TARGET_H / tall
    sprites = []
    for c, x0, y0, x1, y1 in boxes:
        cell = im.crop((x0, y0, x1 + 1, y1 + 1))
        w = max(1, round(cell.width * k)); h = max(1, round(cell.height * k))
        # premultiplied resize so edges don't pick up halo colour
        arr = np.array(cell).astype(np.float32)
        arr[:, :, :3] *= arr[:, :, 3:4] / 255
        sm = Image.fromarray(arr.clip(0, 255).astype(np.uint8)).resize((w, h), Image.LANCZOS)
        al = np.array(cell.getchannel('A').resize((w, h), Image.BOX)).astype(np.float32)
        rgb = np.array(sm)[:, :, :3].astype(np.float32)
        rgb = (rgb * 255 / np.maximum(al[:, :, None], 1)).clip(0, 255)
        sprites.append((rgb.astype(np.uint8), al > 110))
    # one shared palette over all opaque pixels
    allpx = np.concatenate([s[0][s[1]] for s in sprites])
    strip = Image.fromarray(allpx.reshape(1, -1, 3))
    pal_img = strip.quantize(colors=127, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = np.array(pal_img.getpalette()[:127 * 3]).reshape(-1, 3)
    W = max(s[0].shape[1] for s in sprites); H = max(s[0].shape[0] for s in sprites)
    frames = []
    for rgb, m in sprites:
        h, w = m.shape
        q = np.array(Image.fromarray(rgb).quantize(palette=pal_img, dither=Image.Dither.NONE)).astype(np.uint8) + 1
        q[~m] = 0
        f = np.zeros((H, W), np.uint8)
        ox = (W - w) // 2; oy = H - h            # centre x, bottom aligned
        f[oy:oy + h, ox:ox + w] = q
        frames.append(f)
    c565 = [((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3) for r, g, b in pal]

    hp = os.path.join(ROOT, 'firmware', 'LarpCharm', 'pup_sprite.h')
    with open(hp, 'w') as fh:
        fh.write('// generated by firmware/tools/mksprite.py from pup_sheet.png - do not edit\n')
        fh.write('#pragma once\n#include <pgmspace.h>\n')
        fh.write('#define PUP_W %d\n#define PUP_H %d\n#define PUP_N 8\n' % (W, H))
        fh.write('// outfits: %s\n' % ', '.join(NAMES))
        fh.write('static const uint16_t PUP_PAL[%d] PROGMEM = {0x0000,\n' % (len(c565) + 1))
        for i in range(0, len(c565), 12):
            fh.write('  ' + ','.join('0x%04X' % v for v in c565[i:i + 12]) + ',\n')
        fh.write('};\n')
        fh.write('static const uint8_t PUP_PX[PUP_N][PUP_H * PUP_W] PROGMEM = {\n')
        for name, f in zip(NAMES, frames):
            fh.write(' { // %s\n' % name)
            flat = f.flatten()
            for i in range(0, len(flat), 32):
                fh.write('  ' + ','.join(str(v) for v in flat[i:i + 32]) + ',\n')
            fh.write(' },\n')
        fh.write('};\n')

    jp = os.path.join(ROOT, 'pup.js')
    with open(jp, 'w') as fh:
        fh.write('// generated by firmware/tools/mksprite.py - the weather pup, same pixels as the firmware\n')
        fh.write('window.PUP = {w: %d, h: %d, n: 8,\n pal: [%s],\n px: "%s"};\n' % (
            W, H, ','.join('"#%02x%02x%02x"' % tuple(p) for p in pal),
            base64.b64encode(np.stack(frames).tobytes()).decode()))

    # optional strip of all 8 for eyeballing: PUP_PREVIEW=/path/out.png
    prev = Image.new('RGBA', (W * 8, H))
    lut = np.vstack([[0, 0, 0], pal]).astype(np.uint8)
    for i, f in enumerate(frames):
        rgba = np.dstack([lut[f], np.where(f > 0, 255, 0).astype(np.uint8)])
        prev.paste(Image.fromarray(rgba), (i * W, 0))
    if os.environ.get('PUP_PREVIEW'):
        prev.save(os.environ['PUP_PREVIEW'])
    print('pup %dx%d x8, %d colours -> %s, %s' % (W, H, len(c565), hp, jp))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), 'pup_sheet.png'))
