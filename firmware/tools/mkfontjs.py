# Exports the sing-along lettering (P_M, P_L in aafonts.h) for the website, so its preview draws the
# very same 4-bit glyph bitmaps as the charm. Usage: python3 mkfontjs.py aafonts.h sing-font.js
import re, sys, base64
src = open(sys.argv[1]).read()
out = ['// Generated by firmware/tools/mkfontjs.py from aafonts.h: Gloria Hallelujah (SIL Open Font Licence 1.1),',
       '// 4 bits per pixel, the same bitmaps the charm uses for the sing-along. glyphs: [off, w, h, dx, dy, adv]',
       'window.SING_FONTS = {']
for name in ('P_M', 'P_L'):
    bm = re.search(r'const uint8_t %s_bmp\[\] PROGMEM = \{(.*?)\};' % name, src, re.S).group(1)
    data = bytes(int(x, 16) for x in re.findall(r'0x[0-9A-F]{2}', bm))
    gl = re.search(r'const AAGlyph %s_g\[\] PROGMEM = \{(.*?)\n\};' % name, src, re.S).group(1)
    glyphs = [[int(v) for v in g.split(',')] for g in re.findall(r'\{([-0-9,]+)\}', gl)]
    hdr = re.search(r'const AAFont %s = \{ \w+, \w+, (\d+), (\d+), (\d+), (\d+) \};' % name, src)
    first, last, lineH, asc = map(int, hdr.groups())
    out.append('  %s: { first: %d, last: %d, lineH: %d, ascent: %d, glyphs: %s,\n    bmp: "%s" },' %
               (name, first, last, lineH, asc, str(glyphs).replace(' ', ''), base64.b64encode(data).decode()))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
